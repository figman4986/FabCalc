package com.figapps.fractioncalculatorv1

import android.content.Context
import android.database.sqlite.SQLiteDatabase
import androidx.room.Room
import androidx.test.ext.junit.runners.AndroidJUnit4
import androidx.test.platform.app.InstrumentationRegistry
import com.figapps.fractioncalculatorv1.history.HistoryDatabase
import com.figapps.fractioncalculatorv1.wire.MetalType
import com.figapps.fractioncalculatorv1.wire.WireDatasheet
import com.figapps.fractioncalculatorv1.wire.WireProcess
import kotlinx.coroutines.flow.first
import kotlinx.coroutines.runBlocking
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import org.junit.runner.RunWith

/**
 * The real v2 → v3 upgrade, on a device. It builds a database at the *previous* schema by hand,
 * inserts history rows, opens it through Room with the production migrations, and asserts both that
 * the history survives and that the new wire table is usable.
 *
 * Room validates the migrated schema against [HistoryDatabase] as part of opening, so a migration
 * whose SQL does not match the entity fails here too.
 *
 * The checked-in schema snapshot is generated by Room and remains available to future migration tests.
 */
@RunWith(AndroidJUnit4::class)
class WireDatabaseMigrationInstrumentedTest {

    private val databaseName = "wire-migration-test.db"

    @Test
    fun migration2To3_createsTheWireTableAndPreservesHistory() = runBlocking {
        val context: Context = InstrumentationRegistry.getInstrumentation().targetContext
        context.deleteDatabase(databaseName)

        val file = context.getDatabasePath(databaseName)
        file.parentFile?.mkdirs()

        // --- a v2 database, exactly as the previous release left it ---
        val legacy = SQLiteDatabase.openOrCreateDatabase(file, null)
        legacy.execSQL(
            "CREATE TABLE IF NOT EXISTS `history` (" +
                "`id` INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL, " +
                "`toolId` TEXT NOT NULL, " +
                "`toolName` TEXT NOT NULL, " +
                "`inputs` TEXT NOT NULL, " +
                "`result` TEXT NOT NULL, " +
                "`detail` TEXT NOT NULL, " +
                "`timestamp` INTEGER NOT NULL)"
        )
        legacy.execSQL("CREATE INDEX IF NOT EXISTS index_history_timestamp ON history(timestamp)")
        legacy.execSQL("CREATE INDEX IF NOT EXISTS index_history_toolId ON history(toolId)")
        legacy.execSQL(
            "INSERT INTO history (toolId, toolName, inputs, result, detail, timestamp) " +
                "VALUES ('offset', 'Offset Calculator', 'in', 'out', 'detail', 42)"
        )
        legacy.version = 2
        legacy.close()

        // --- open with the current schema: the migration must run and validate ---
        val database = Room.databaseBuilder(context, HistoryDatabase::class.java, databaseName)
            .addMigrations(*HistoryDatabase.ALL_MIGRATIONS)
            .build()
        try {
            val history = database.historyDao().observeAll().first()
            assertEquals("history rows must survive the schema bump", 1, history.size)
            assertEquals("Offset Calculator", history.first().toolName)
            assertEquals("in", history.first().inputs)
            assertEquals("out", history.first().result)
            assertEquals(42L, history.first().timestamp)

            val id = database.wireDatasheetDao().insert(sampleDatasheet())
            assertTrue("the new wire table must be usable after the migration", id > 0)
            assertEquals(1, database.wireDatasheetDao().count())
        } finally {
            database.close()
            context.deleteDatabase(databaseName)
        }
    }

    private fun sampleDatasheet() = WireDatasheet(
        id = 0,
        fileName = "abc.pdf",
        sha256 = "0".repeat(64),
        brand = "Brand",
        productName = "Product",
        awsClassification = "ER70S-6",
        metalType = MetalType.CARBON_STEEL,
        process = WireProcess.SOLID_GMAW,
        wireSizeMm = 0.9,
        notes = null,
        createdAt = 1,
        updatedAt = 1,
    )
}
